/**
 * Regenerates src/human/makehuman-pins.ts: every CC0 asset file of the
 * MakeHuman commit below (base mesh, targets, rig, eyes), with its exact size
 * and SHA-256. Downloads each file once into the forge cache so the pins are
 * computed from the bytes themselves. Run with `pnpm --filter @framefields/forge pin:makehuman`.
 */
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { MAKEHUMAN_SOURCE } from "../src/human/source.js";
import { humanCacheDir } from "../src/human/store.js";

const KEEP =
	/^makehuman\/data\/(3dobjs\/base\.obj|rigs\/default\.mhskel|rigs\/default_weights\.mhw|targets\/.+\.target|eyes\/.+)$/;

const { repo, commit } = MAKEHUMAN_SOURCE;
const tree = (await (
	await fetch(
		`https://api.github.com/repos/${repo}/git/trees/${commit}?recursive=1`,
	)
).json()) as {
	truncated: boolean;
	tree: { path: string; type: string; size?: number }[];
};
if (tree.truncated) throw new Error("tree listing truncated");
const files = tree.tree.filter((t) => t.type === "blob" && KEEP.test(t.path));
const root = humanCacheDir();
const pins: [string, number, string][] = [];
let done = 0;
const queue = [...files];
await Promise.all(
	Array.from({ length: 16 }, async () => {
		for (let f = queue.shift(); f; f = queue.shift()) {
			const url = `https://raw.githubusercontent.com/${repo}/${commit}/${f.path}`;
			const res = await fetch(url);
			if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
			const bytes = new Uint8Array(await res.arrayBuffer());
			if (bytes.byteLength !== f.size)
				throw new Error(
					`${f.path}: ${bytes.byteLength} bytes, tree says ${f.size}`,
				);
			const rel = f.path.replace(/^makehuman\/data\//, "");
			const dest = join(root, rel);
			await mkdir(dirname(dest), { recursive: true });
			await writeFile(dest, bytes);
			pins.push([
				rel,
				bytes.byteLength,
				createHash("sha256").update(bytes).digest("hex"),
			]);
			if (++done % 200 === 0) console.log(`${done}/${files.length}`);
		}
	}),
);
pins.sort((a, b) => (a[0] < b[0] ? -1 : 1));
const out = join(import.meta.dirname, "../src/human/makehuman-pins.ts");
await writeFile(
	out,
	`// biome-ignore-all format: generated by scripts/pin-makehuman.ts
// biome-ignore-all lint: generated data
/** Every pinned MakeHuman asset file: [path under makehuman/data/, bytes, SHA-256]. Generated by \`pnpm pin:makehuman\`. */
export const MAKEHUMAN_PINS: { commit: string; files: [string, number, string][] } = { commit: "${commit}", files: ${JSON.stringify(pins)} };
`,
);
console.log(
	out,
	pins.length,
	"files",
	pins.reduce((s, p) => s + p[1], 0),
	"bytes",
);
process.exit(0);
